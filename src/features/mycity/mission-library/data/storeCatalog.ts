export function getStoreItemById(itemId: string): StoreItem | undefined {
  return storeCatalog.find((item) => item.id === itemId);
}

export function getStoreItemsByBudgetScope(
  budgetScope: StoreItem["budgetScope"],
): StoreItem[] {
  return storeCatalog.filter((item) => item.budgetScope === budgetScope);
}

export function getRequiredStoreItems(): StoreItem[] {
  return storeCatalog.filter((item) => item.required && item.minQuantity > 0);
}
